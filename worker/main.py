#!/usr/bin/env python3
"""P0a inference worker: one job in, one JSON result out. No synthetic fallback."""
from __future__ import annotations
import argparse
import contextlib
import json
import os
from pathlib import Path
import subprocess
import sys
import time
import wave

def pipeline_version():
    path = Path(__file__).resolve().parents[1] / 'pipeline-version.json'
    version = json.loads(path.read_text())['pipelineVersion']
    if not isinstance(version, str) or not version.strip():
        raise ValueError('Invalid pipelineVersion in pipeline-version.json')
    return version


class JobError(Exception):
    def __init__(self, code, message, reject=False):
        super().__init__(message)
        self.code, self.reject = code, reject


def command(args, timeout=120):
    try:
        return subprocess.run(args, check=True, capture_output=True, timeout=timeout).stdout
    except FileNotFoundError:
        raise JobError('ffmpeg_unavailable', '请安装 ffmpeg 和 ffprobe。')
    except subprocess.TimeoutExpired:
        raise JobError('media_timeout', '视频处理超时，请上传更短的视频。', True)
    except subprocess.CalledProcessError as e:
        raise JobError('invalid_video', e.stderr.decode(errors='replace')[-1000:], True)


def ingest(args, output):
    import numpy as np
    from algorithms import capture_timestamps
    info = json.loads(command(['ffprobe', '-v', 'error', '-show_streams', '-show_format', '-of', 'json', args.input]))
    streams = info.get('streams', [])
    stream = next((s for s in streams if s.get('codec_type') == 'video'), None)
    if not stream:
        raise JobError('no_video_stream', '文件中没有可解码的视频轨道。', True)
    width, height = int(stream['width']), int(stream['height'])
    if width * height > 3840 * 2160:
        raise JobError('resolution_too_large', '本地分析仅接受不超过 4K 的视频。', True)
    rotations = [s.get('rotation', 0) for s in stream.get('side_data_list', [])]
    rotation = int(float(stream.get('tags', {}).get('rotate', rotations[0] if rotations else 0))) % 360
    if rotation in (90, 270):
        width, height = height, width
    declared_duration = float(stream.get('duration', info.get('format', {}).get('duration', 0)))
    if declared_duration > 60 or declared_duration < 0:
        raise JobError('clip_too_long', '请截取 60 秒以内的视频。', True)
    raw_frames = json.loads(command(['ffprobe', '-v', 'error', '-select_streams', 'v:0', '-show_frames',
        '-show_entries', 'frame=best_effort_timestamp_time', '-of', 'json', args.input])).get('frames', [])
    if len(raw_frames) < 3 or len(raw_frames) > 20000:
        raise JobError('invalid_frame_count', '视频需包含 3 至 20000 帧。', True)
    try:
        playback = np.array([float(f['best_effort_timestamp_time']) for f in raw_frames])
        timestamps, fps = capture_timestamps(playback, args.capture_fps)
    except (KeyError, ValueError) as e:
        raise JobError(str(e), '无法确定连续的真实采集时间。可变速视频请导出原始片段。', True)
    tags = json.dumps({**info.get('format', {}).get('tags', {}), **stream.get('tags', {})}).lower()
    remap_hint = any(token in tags for token in ['slow.motion', 'slow-motion', 'slowmotion', 'slow motion', 'time.remap', 'time-remap'])
    if remap_hint and args.capture_fps is None:
        raise JobError('capture_timing_required', '检测到慢动作标记，请提供确认过的采集帧率或上传原始视频。', True)
    video_start_time = float(playback[0])
    playback -= playback[0]
    remapped = abs(float(timestamps[-1] - playback[-1])) > .02
    if fps < 15 or fps > 480 or timestamps[-1] > 60:
        raise JobError('unsupported_capture_rate', '仅支持 15–480fps、60 秒以内的视频。', True)
    # Decode through ffmpeg with rotation applied, and normalize the proxy clock to
    # the capture clock. No extra frames are generated by the muxer.
    clock_filter = f'settb=AVTB,setpts=N/({args.capture_fps:.12f}*TB)' if args.capture_fps is not None else 'setpts=PTS-STARTPTS'
    command(['ffmpeg', '-nostdin', '-v', 'error', '-y', '-i', args.input, '-map', '0:v:0', '-an',
             '-vf', f'{clock_filter},scale=trunc(iw/2)*2:trunc(ih/2)*2',
             '-c:v', 'libx264', '-preset', 'veryfast', '-crf', '21', '-pix_fmt', 'yuv420p',
             '-fps_mode', 'passthrough', '-enc_time_base', '1:90000', '-video_track_timescale', '90000', '-movflags', '+faststart', str(output/'proxy.mp4')])
    audio = any(s.get('codec_type') == 'audio' for s in streams)
    # Audio in remapped footage cannot safely be recovered from one FPS hint.
    if audio and not remapped:
        audio_stream = next(s for s in streams if s.get('codec_type') == 'audio')
        offset = float(audio_stream.get('start_time', video_start_time)) - video_start_time
        audio_filter = f'adelay={max(0, offset)*1000:.4f}:all=1' if offset >= 0 else f'atrim=start={-offset:.8f}'
        command(['ffmpeg', '-nostdin', '-v', 'error', '-y', '-i', args.input, '-map', '0:a:0',
                 '-af', audio_filter, '-ac', '1', '-ar', '16000', '-c:a', 'pcm_s16le', str(output/'audio.wav')])
    video = {"id": args.video_id, "storageKey": Path(args.input).name, "proxyKey": 'proxy.mp4',
             "width": width - width % 2, "height": height - height % 2,
             "captureFps": fps, "frameCount": len(timestamps),
             "durationSec": float(timestamps[-1] + np.median(np.diff(timestamps))),
             "hasAudio": audio, "timeRemapped": remapped or remap_hint}
    return video, timestamps, audio and not remapped


class Tracker:
    """Gated target continuity; ambiguous association becomes a missing frame."""
    def __init__(self, target=None):
        self.target, self.previous, self.last_time = target, None, None
        self.ever_locked = False

    def choose(self, candidates, t):
        import numpy as np
        usable = []
        for index, points in enumerate(candidates):
            visible = points[:17, 2] >= .4
            if visible.sum() < 5:
                continue
            xy = points[:17, :2][visible]
            center = np.median(xy, axis=0)
            extent = np.max(xy, axis=0) - np.min(xy, axis=0)
            usable.append((index, center, float(np.prod(extent)), xy))
        if not usable:
            return None
        if self.previous is None:
            if self.ever_locked:
                return None  # never silently lock to a different person after losing target
            if self.target is not None:
                ranked = sorted(usable, key=lambda p: np.min(np.linalg.norm(p[3]-self.target, axis=1)))
                if np.min(np.linalg.norm(ranked[0][3]-self.target, axis=1)) > .25:
                    return None
            else:
                ranked = sorted(usable, key=lambda p: p[2], reverse=True)
                if len(ranked) > 1 and ranked[0][2] < ranked[1][2] * 1.3:
                    raise JobError('target_selection_required', '多人入镜且目标不明确，请在预览中点选球员。', True)
        else:
            if t - self.last_time > .5:
                return None
            ranked = sorted(usable, key=lambda p: np.linalg.norm(p[1]-self.previous))
            distance = np.linalg.norm(ranked[0][1]-self.previous)
            if distance > .08 + (t-self.last_time) * .8:
                return None
            if len(ranked) > 1 and np.linalg.norm(ranked[1][1]-self.previous) - distance < .03:
                return None
        selected = ranked[0]
        self.previous, self.last_time, self.ever_locked = selected[1], t, True
        return selected[0]


def load_model():
    try:
        import cv2
        from rtmlib import Wholebody
    except ImportError as e:
        raise JobError('model_not_configured', f'姿态推理依赖尚未安装：{e}。请参阅 worker/README.md。')
    det, pose = os.getenv('RTMLIB_DET_MODEL'), os.getenv('RTMLIB_POSE_MODEL')
    kwargs = {'mode': 'balanced', 'to_openpose': False, 'backend': 'onnxruntime', 'device': os.getenv('POSE_DEVICE', 'cpu')}
    if det and pose:
        if not Path(det).is_file() or not Path(pose).is_file():
            raise JobError('model_not_configured', '检测模型或姿态模型文件不存在。')
        kwargs.update(det=det, pose=pose,
                      det_input_size=tuple(int(x) for x in os.getenv('RTMLIB_DET_SIZE', '640,640').split(',')),
                      pose_input_size=tuple(int(x) for x in os.getenv('RTMLIB_POSE_SIZE', '192,256').split(',')))
    elif os.getenv('ALLOW_MODEL_DOWNLOAD') != '1':
        raise JobError('model_not_configured', '请配置 RTMLIB_DET_MODEL 和 RTMLIB_POSE_MODEL，或显式启用 ALLOW_MODEL_DOWNLOAD=1。')
    try:
        return Wholebody(**kwargs)
    except Exception as e:
        raise JobError('model_initialization_failed', f'姿态模型加载失败：{e}')


def infer(proxy, times, video, target):
    import numpy as np
    model = load_model()
    import cv2
    from algorithms import to_cwb65
    frame_count = len(times)
    keypoints = np.zeros((frame_count, 65, 3), dtype=np.float32)
    keypoints[:, :, :2] = np.nan
    multi_person, brightness = False, []
    tracker = Tracker(target)
    capture = cv2.VideoCapture(str(proxy))
    seen = 0
    try:
        # Infer every decoded frame once, keeping target association continuous.
        # Unsampled frames would otherwise appear as missing poses in playback.
        while True:
            ok, frame = capture.read()
            if not ok:
                break
            index = seen
            seen += 1
            if index >= frame_count:
                raise JobError('decode_frame_mismatch', '代理视频帧数与时间戳不一致。', True)
            h, w = frame.shape[:2]
            points, scores = model(frame)
            candidates = [to_cwb65(p, s, w, h) for p, s in zip(points, scores)]
            multi_person |= len(candidates) > 1
            selected = tracker.choose(candidates, float(times[index]))
            if selected is not None:
                keypoints[index] = candidates[selected]
            brightness.append(float(np.mean(cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY))))
    finally:
        capture.release()
    if seen != frame_count:
        raise JobError('decode_frame_mismatch', '解码帧数与采集时间戳不一致。', True)
    return keypoints, multi_person, float(np.mean(brightness)) if brightness else 0, list(range(frame_count))


def run(args):
    output = Path(args.output_dir)
    output.mkdir(parents=True, exist_ok=True)
    analysis = {"id": args.analysis_id, "videoId": args.video_id, "status": 'running',
                "schemaVersion": '0.2.0', "pipelineVersion": pipeline_version(),
                "userInput": {"swingType": args.swing_type}, "swings": [], "metrics": [], "diagnoses": [], "stageTimingsMs": {}}
    if args.target_point:
        analysis['userInput']['targetPoint'] = args.target_point
    video = None
    started = time.perf_counter()
    mark = started
    def timing(name):
        nonlocal mark
        now = time.perf_counter()
        analysis['stageTimingsMs'][name] = round((now-mark)*1000, 2)
        mark = now
    try:
        import numpy as np
        from algorithms import smooth_pose, audio_onsets, detect_swings, quality_report, SMOOTHING
        video, timestamps, usable_audio = ingest(args, output)
        timing('ingest')
        pose, multi_person, light, sampled = infer(output/'proxy.mp4', timestamps, video, args.target_point)
        timing('pose_and_tracking')
        pose = smooth_pose(pose, timestamps)
        timing('smooth')
        analysis['quality'] = quality_report(pose, video['captureFps'], light, multi_person, video['width']/video['height'], sampled)
        if video['timeRemapped']:
            analysis['quality']['issues'].append({'code': 'capture_fps_user_confirmed', 'severity': 'info'})
        if not usable_audio:
            analysis['quality']['issues'].append({'code': 'visual_only', 'severity': 'info'})
        timing('quality')
        if not analysis['quality']['usable']:
            raise JobError('body_not_visible', '目标球员的身体关键点不足，请保持全身入镜并减少遮挡。', True)
        onsets = []
        if usable_audio:
            with wave.open(str(output/'audio.wav'), 'rb') as audio:
                samples = np.frombuffer(audio.readframes(audio.getnframes()), dtype='<i2') / 32768.
                onsets = audio_onsets(samples, audio.getframerate())
        analysis['swings'] = detect_swings(pose, timestamps, onsets, args.swing_type, video['width']/video['height'])
        timing('events')
        if not analysis['swings']:
            raise JobError('no_swing_detected', '未找到可信的挥拍事件，请上传包含完整挥拍的视频。', True)
        timestamps.astype('<f4').tofile(output/'timestamps.f32')
        pose.astype('<f4').tofile(output/'keypoints.f32')
        analysis['target'] = {'trackId': 1, 'lockedBy': 'user' if args.target_point else 'auto'}
        analysis['skeleton'] = {'spec': 'cwb-65', 'source': 'mono-2d', 'coordSpace': 'image-normalized',
            'frameCount': len(timestamps), 'timestampsKey': 'timestamps.f32', 'keypointsKey': 'keypoints.f32',
            'smoothing': {'method': 'one-euro', 'params': SMOOTHING}}
        analysis['status'] = 'succeeded'
        result = {'video': video, 'analysis': analysis}
    except Exception as error:
        rejected = isinstance(error, JobError) and error.reject
        analysis['status'] = 'rejected_quality' if rejected else 'failed'
        code = error.code if isinstance(error, JobError) else 'worker_error'
        if isinstance(error, ImportError):
            code = 'worker_dependencies_missing'
        if 'quality' not in analysis:
            analysis['quality'] = {'fpsTier': 'low', 'view': 'unknown', 'viewConfidence': 0, 'bodyVisibleRatio': 0,
                                   'lighting': 'ok', 'multiPerson': False, 'issues': [], 'usable': False}
        analysis['quality']['usable'] = False
        analysis['quality']['issues'].append({'code': code, 'severity': 'block'})
        result = {'video': video, 'analysis': analysis, 'error': str(error), 'errorCode': code}
    analysis['stageTimingsMs']['total'] = round((time.perf_counter()-started)*1000, 2)
    (output/'result.json').write_text(json.dumps(result, ensure_ascii=False, allow_nan=False, indent=2))
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--input', required=True)
    parser.add_argument('--output-dir', required=True)
    parser.add_argument('--analysis-id', required=True)
    parser.add_argument('--video-id', required=True)
    parser.add_argument('--swing-type', choices=['smash', 'clear'], default='smash')
    parser.add_argument('--target-point', type=lambda s: [float(x) for x in s.split(',')])
    parser.add_argument('--capture-fps', type=float)
    args = parser.parse_args()
    if args.target_point and (len(args.target_point) != 2 or any(not 0 <= x <= 1 for x in args.target_point)):
        parser.error('target-point must be x,y in [0,1]')
    # Inference libraries print progress to stdout; preserve a single JSON protocol.
    with contextlib.redirect_stdout(sys.stderr):
        result = run(args)
    print(json.dumps(result, ensure_ascii=False, allow_nan=False))


if __name__ == '__main__':
    main()
